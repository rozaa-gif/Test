const LANG_KEY = "peppharma_lang";

function getLang() {
  return localStorage.getItem(LANG_KEY) || "no";
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

function t(key) {
  const lang = getLang();
  const parts = key.split(".");
  let node = translations[lang];
  for (const part of parts) {
    if (node == null) break;
    node = node[part];
  }
  if (node == null) {
    // fall back to Norwegian if a key is missing in the active language
    node = translations.no;
    for (const part of parts) {
      if (node == null) break;
      node = node[part];
    }
  }
  return node != null ? node : key;
}

function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.setAttribute("placeholder", t(key));
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  document.dispatchEvent(new CustomEvent("i18n:applied", { detail: { lang } }));
}

function initLangSwitch() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang");
      setLang(lang);
      applyI18n();
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyI18n();
  initLangSwitch();
});
